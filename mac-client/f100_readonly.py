def _read_lq_fixture(path: str) -> bytes:
    """Load a captured LQ payload for offline decoding. Accepts either a
    raw binary file, or a text file of whitespace-separated hex bytes
    (e.g. `00 F3 00 01 ...`, newlines and comments starting with `#`
    allowed) — this is deliberately lenient about capture formats since
    fixtures may come from a hex dump, a pcap byte extract, or manual
    transcription of a Camera Companion capture."""
    raw = Path(path).read_bytes()
    try:
        text = raw.decode("ascii")
    except UnicodeDecodeError:
        return raw
    tokens = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            tokens.extend(line.split())
    if tokens and all(len(t) == 2 and all(c in "0123456789abcdefABCDEF" for c in t) for t in tokens):
        return bytes(int(t, 16) for t in tokens)
    return raw


_MISSING = object()


def load_parity_reference(path: Path) -> dict:
    """Load and validate an offline semantic-parity reference.

    The source block records an evidence claim supplied by the file author. It
    is validated for internal consistency, but loading it does not authenticate
    the claimed application or promote synthetic data to hardware evidence.
    """
    try:
        document = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ProtocolError(f"cannot read parity reference {path}: {exc}") from exc

    if not isinstance(document, dict):
        raise ProtocolError("parity reference must be a JSON object")
    if document.get("schema") != PARITY_REFERENCE_SCHEMA:
        raise ProtocolError(
            f"parity reference schema must be {PARITY_REFERENCE_SCHEMA!r}"
        )

    source = document.get("source")
    if not isinstance(source, dict):
        raise ProtocolError("parity reference source must be an object")
    application = source.get("application")
    expected_role = PARITY_REFERENCE_ROLES.get(application)
    if expected_role is None:
        raise ProtocolError(
            "reference source application must be one of: "
            + ", ".join(PARITY_REFERENCE_ROLES)
        )
    if source.get("reference_role") != expected_role:
        raise ProtocolError(
            f"{application} must use reference_role {expected_role!r}"
        )
    evidence_kind = source.get("evidence_kind")
    if evidence_kind not in PARITY_EVIDENCE_KINDS:
        raise ProtocolError(
            "reference source evidence_kind must be one of: "
            + ", ".join(sorted(PARITY_EVIDENCE_KINDS))
        )
    hardware_validated = source.get("hardware_validated")
    if not isinstance(hardware_validated, bool):
        raise ProtocolError("reference source hardware_validated must be boolean")
    if application == "synthetic":
        if evidence_kind != "synthetic":
            raise ProtocolError("synthetic references must use evidence_kind 'synthetic'")
        if hardware_validated:
            raise ProtocolError("synthetic references cannot be hardware-validated")
    elif evidence_kind == "synthetic":
        raise ProtocolError("application references cannot use synthetic evidence_kind")

    if hardware_validated:
        provenance = source.get("provenance")
        if not isinstance(provenance, dict):
            raise ProtocolError(
                "hardware-validated application references require provenance"
            )
        for field in (
            "run_id",
            "application_version",
            "approval_scope",
            "camera_state",
        ):
            if not isinstance(provenance.get(field), str) or not provenance[field].strip():
                raise ProtocolError(
                    f"hardware provenance {field} must be a non-empty string"
                )
        captured_at = provenance.get("captured_at_utc")
        if not isinstance(captured_at, str):
            raise ProtocolError(
                "hardware provenance captured_at_utc must be an ISO-8601 string"
            )
        try:
            captured_datetime = datetime.fromisoformat(
                captured_at.replace("Z", "+00:00")
            )
        except ValueError as exc:
            raise ProtocolError(
                "hardware provenance captured_at_utc must be valid ISO-8601"
            ) from exc
        if (
            captured_datetime.tzinfo is None
            or captured_datetime.utcoffset() != timedelta(0)
        ):
            raise ProtocolError(
                "hardware provenance captured_at_utc must use UTC"
            )
        capture_hash = provenance.get("raw_capture_sha256")
        if not (
            isinstance(capture_hash, str)
            and len(capture_hash) == 64
            and all(character in "0123456789abcdef" for character in capture_hash)
        ):
            raise ProtocolError(
                "hardware provenance raw_capture_sha256 must be 64 lowercase hex characters"
            )
        capture_size = provenance.get("raw_capture_size_bytes")
        if (
            not isinstance(capture_size, int)
            or isinstance(capture_size, bool)
            or capture_size <= 0
        ):
            raise ProtocolError(
                "hardware provenance raw_capture_size_bytes must be a positive integer"
            )

    if not isinstance(document.get("expected"), dict):
        raise ProtocolError("parity reference expected must be an object")
    return document


def _json_path(parent: str, key) -> str:
    if isinstance(key, int):
        return f"{parent}[{key}]"
    return f"{parent}.{key}"


def _append_parity_comparisons(expected, actual, path: str, output: list[dict]) -> None:
    if expected is None:
        output.append(
            {
                "path": path,
                "status": "UNKNOWN",
                "reference": None,
                "actual": "<missing>" if actual is _MISSING else actual,
            }
        )
        return

    if isinstance(expected, dict):
        if not isinstance(actual, dict):
            output.append(
                {
                    "path": path,
                    "status": "DIFFER",
                    "reference": expected,
                    "actual": "<missing>" if actual is _MISSING else actual,
                }
            )
            return
        for key, value in expected.items():
            _append_parity_comparisons(
                value, actual.get(key, _MISSING), _json_path(path, key), output
            )
        return

    if isinstance(expected, list):
        if not isinstance(actual, list):
            output.append(
                {
                    "path": path,
                    "status": "DIFFER",
                    "reference": expected,
                    "actual": "<missing>" if actual is _MISSING else actual,
                }
            )
            return
        output.append(
            {
                "path": f"{path}.length",
                "status": "MATCH" if len(expected) == len(actual) else "DIFFER",
                "reference": len(expected),
                "actual": len(actual),
            }
        )
        for index, value in enumerate(expected):
            item = actual[index] if index < len(actual) else _MISSING
            _append_parity_comparisons(
                value, item, _json_path(path, index), output
            )
        return

    output.append(
        {
            "path": path,
            "status": "MATCH" if actual is not _MISSING and expected == actual else "DIFFER",
            "reference": expected,
            "actual": "<missing>" if actual is _MISSING else actual,
        }
    )


def compare_lq_reference(reference: dict, decoded: dict) -> dict:
    """Compare a decoded LQ result against the reference's asserted subset."""
    comparisons: list[dict] = []
    _append_parity_comparisons(reference["expected"], decoded, "$", comparisons)
    counts = {
        status.lower(): sum(item["status"] == status for item in comparisons)
        for status in ("MATCH", "DIFFER", "UNKNOWN")
    }
    overall = "DIFFER" if counts["differ"] else (
        "UNKNOWN" if counts["unknown"] else "MATCH"
    )
    source = dict(reference["source"])
    if source["application"] == "synthetic":
        claim_limit = (
            "Synthetic structural match only; this cannot establish parity with "
            "Nikon Photo Secretary II, a physical F100, or Nikon specifications."
        )
    elif not source["hardware_validated"]:
        claim_limit = (
            "Reference metadata is not hardware-validated; a match does not establish "
            "live F100 parity."
        )
    else:
        claim_limit = (
            "The reference file asserts hardware evidence. This tool compares supplied "
            "semantics only and does not authenticate provenance or hardware safety."
        )
    return {
        "schema": PARITY_REFERENCE_SCHEMA,
        "reference_source": source,
        "overall": overall,
        "summary": counts,
        "comparisons": comparisons,
        "_claim_limit": claim_limit,
    }


