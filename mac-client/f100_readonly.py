# name -> real filename in evidence/static/camera_companion/ (LQ_VALUE_TABLES.md
# §1). Only "shutter" breaks the naive `lq_{name}_table.tsv` pattern.
_VALUE_TABLE_FILENAMES = {
    "shutter": "lq_shutter_speed_table.tsv",
    "aperture": "lq_aperture_table.tsv",
    "focal_length": "lq_focal_length_table.tsv",
    "ev": "lq_ev_compensation_table.tsv",
}


def _table_directory(directory: Optional[Path] = None) -> Path:
    return Path(directory) if directory is not None else Path(__file__).resolve().parent


def _handle_missing_table(path: Path, policy: str) -> None:
    message = f"value table missing: {path}"
    if policy == "strict":
        raise FileNotFoundError(message)
    if policy == "warn":
        warnings.warn(message, RuntimeWarning, stacklevel=3)
    elif policy != "raw":
        raise ValueError("table policy must be one of: raw, warn, strict")


def _handle_table_problem(message: str, policy: str) -> None:
    if policy == "strict":
        raise ProtocolError(message)
    if policy == "warn":
        warnings.warn(message, RuntimeWarning, stacklevel=3)


def _load_value_table(
    name: str,
    *,
    directory: Optional[Path] = None,
    missing_policy: str = "raw",
) -> Optional[dict[int, str]]:
    """Load an optional raw->display TSV copied from the audit archive's
    evidence/static/camera_companion/ directory. Deliberately NOT
    hardcoded in this script — see module docstring.

    Columns are `raw_hex\traw_decimal\tdisplay` with CSV-style quoting
    (e.g. shutter raw 0xFD's display column is quoted and doubled to
    encode a trailing inch/seconds mark, displaying as 1.5 seconds) — this
    must go through `csv.reader`, not a bare `str.split("\\t")`, or both
    the quoting and the intended display column get mangled."""
    try:
        filename = _VALUE_TABLE_FILENAMES[name]
    except KeyError as exc:
        raise ValueError(f"unknown value table name: {name}") from exc
    if missing_policy not in {"raw", "warn", "strict"}:
        raise ValueError("table policy must be one of: raw, warn, strict")
    path = _table_directory(directory) / filename
    if not path.exists():
        _handle_missing_table(path, missing_policy)
        return None
    table: dict[int, str] = {}
    with path.open(encoding="utf-8", newline="") as f:
        reader = csv.reader(f, delimiter="\t")
        header = next(reader, None)
        if header is None or header[:3] != ["raw_hex", "raw_decimal", "display"]:
            _handle_table_problem(f"invalid value-table header: {path}", missing_policy)
        for line_number, row in enumerate(reader, start=2):
            if len(row) < 3:
                _handle_table_problem(
                    f"{path}:{line_number}: fewer than 3 columns", missing_policy
                )
                continue
            try:
                raw = int(row[0], 0)
                decimal = int(row[1], 10)
            except ValueError:
                _handle_table_problem(
                    f"{path}:{line_number}: invalid numeric value", missing_policy
                )
                continue
            if not (0 <= raw <= 0xFF) or raw != decimal or raw in table:
                _handle_table_problem(
                    f"{path}:{line_number}: inconsistent or duplicate raw value",
                    missing_policy,
                )
                continue
            table[raw] = row[2]
    return table


def validate_value_tables(directory: Optional[Path] = None) -> dict:
    """Validate all four optional TSVs without opening a serial device."""
    base = _table_directory(directory)
    report: dict = {"directory": str(base), "tables": {}, "ok": True}

    for name, filename in _VALUE_TABLE_FILENAMES.items():
        path = base / filename
        item = {"file": filename, "present": path.is_file(), "rows": 0, "errors": []}
        report["tables"][name] = item
        if not path.is_file():
            item["errors"].append("missing")
            report["ok"] = False
            continue

        seen: set[int] = set()
        try:
            with path.open(encoding="utf-8", newline="") as f:
                reader = csv.reader(f, delimiter="\t")
                header = next(reader, None)
                if header is None or header[:3] != ["raw_hex", "raw_decimal", "display"]:
                    item["errors"].append("invalid header")
                for line_number, row in enumerate(reader, start=2):
                    if len(row) < 3:
                        item["errors"].append(f"line {line_number}: fewer than 3 columns")
                        continue
                    try:
                        raw = int(row[0], 0)
                        decimal = int(row[1], 10)
                    except ValueError:
                        item["errors"].append(f"line {line_number}: invalid numeric value")
                        continue
                    if not (0 <= raw <= 0xFF):
                        item["errors"].append(f"line {line_number}: raw value outside byte range")
                    if raw != decimal:
                        item["errors"].append(f"line {line_number}: hex/decimal mismatch")
                    if raw in seen:
                        item["errors"].append(f"line {line_number}: duplicate raw value 0x{raw:02x}")
                    seen.add(raw)
                    item["rows"] += 1
        except (OSError, UnicodeError, csv.Error) as exc:
            item["errors"].append(f"read error: {exc}")

        if item["errors"]:
            report["ok"] = False

    return report


def decode_lq(
    data: bytes,
    *,
    table_dir: Optional[Path] = None,
    table_policy: str = "formula",
) -> dict:
    if len(data) < 1:
        raise ProtocolError("LQ response empty")

    mode = data[0]
    if mode not in (0x00, 0x01):
        raise ProtocolError(f"unexpected LQ mode byte 0x{mode:02x} (expected 00 or 01)")
    detailed = mode == 0x01
    record_size = 13 if detailed else 5

    tables = {
        name: _load_value_table(
            name, directory=table_dir, missing_policy="raw" if table_policy == "formula" else table_policy
        )
        for name in _VALUE_TABLE_FILENAMES
    }

    sources = {}

    def lookup(table_name: str, raw: int) -> str:
        table = tables[table_name]
        if table is not None and raw in table:
            label, source = table[raw], "external_table"
        elif table_policy == "formula":
            label, source = f100_numeric.display(table_name, raw)
        else:
            label, source = f"0x{raw:02x}", "raw"
        sources.setdefault(table_name, {})[f"0x{raw:02x}"] = source
        return label

    rolls = []
    i = 1
    while i < len(data):
        if data[i] != 0xF3:
            raise ProtocolError(f"expected roll start 0xF3 at offset {i}, got 0x{data[i]:02x}")
        if i + 3 > len(data):
            raise ProtocolError("truncated roll header")
        roll_number = int.from_bytes(data[i + 1 : i + 3], "big")
        i += 3
        frames = []
        film_speed_code: Optional[int] = None
        while i < len(data):
            # The trailer is exactly one byte immediately before 0xFD (per
            # STATIC_ANALYSIS.md §7: "FD 앞의 1바이트는 롤 객체의 +0x04
            # 필드"). BUT 0xFD is also a *valid* shutter-speed raw code
            # (lq_shutter_speed_table.tsv: 0xFD -> 1.5") that can appear
            # as a normal record byte — so "next byte is 0xFD" alone is
            # not sufficient, or a record with that shutter value gets
            # misparsed as a truncated roll (corrective audit P0). Only
            # accept this as the real trailer when the FD is also at a
            # genuine roll boundary: either the last 2 bytes of the whole
            # buffer, or immediately followed by the next roll's F3.
            if (
                i + 1 < len(data)
                and data[i + 1] == 0xFD
                and (i + 2 == len(data) or data[i + 2] == 0xF3)
            ):
                film_speed_code = data[i]
                i += 2
                break
            if i + record_size > len(data):
                raise ProtocolError("truncated frame record")
            rec = data[i : i + record_size]
            frame = {
                "frame_number": rec[0],
                "shutter_speed_raw": f"0x{rec[1]:02x}",
                "shutter_speed": lookup("shutter", rec[1]),
                "aperture_raw": f"0x{rec[2]:02x}",
                "aperture": lookup("aperture", rec[2]),
                "focal_length_raw": f"0x{rec[3]:02x}",
                "focal_length": lookup("focal_length", rec[3]),
                "flash_flags_raw": f"0x{rec[4]:02x}",
                # Flash type is bits 1:0 only; bit 4 (multiple_exposure) and
                # other bits are independent/reserved and never affect this
                # label. Real-hardware evidence (Roll 47/48, 2026-09-19):
                # 0=off, 1=non_ttl, 3=ttl observed; 2 is reserved/unobserved.
                "flash_type": {0: "off", 1: "non_ttl", 3: "ttl"}.get(
                    rec[4] & 0b11, f"unknown(0x{rec[4] & 0b11:02x})"
                ),
                "multiple_exposure": bool(rec[4] & 0b10000),
            }
            if detailed:
                sync_bits = (rec[12] >> 4) & 0b111
                frame.update(
                    {
                        "lens_shortest_focal_raw": f"0x{rec[5]:02x}",
                        "lens_shortest_focal": lookup("focal_length", rec[5]),
                        "lens_longest_focal_raw": f"0x{rec[6]:02x}",
                        "lens_longest_focal": lookup("focal_length", rec[6]),
                        "max_aperture_short_raw": f"0x{rec[7]:02x}",
                        "max_aperture_short": lookup("aperture", rec[7]),
                        "max_aperture_long_raw": f"0x{rec[8]:02x}",
                        "max_aperture_long": lookup("aperture", rec[8]),
                        "manual_ev_diff_raw": f"0x{rec[9]:02x}",
                        "manual_ev_diff": lookup("ev", rec[9]),
                        "exposure_comp_raw": f"0x{rec[10]:02x}",
                        "exposure_comp": lookup("ev", rec[10]),
                        "flash_comp_raw": f"0x{rec[11]:02x}",
                        "flash_comp": lookup("ev", rec[11]),
                        "mode_flags_raw": f"0x{rec[12]:02x}",
                        "meter_mode": ["matrix", "spot", "center_weighted", "center_weighted"][
                            rec[12] & 0b11
                        ],
                        "exposure_mode": ["P", "S", "A", "M"][(rec[12] >> 2) & 0b11],
                        # Real-hardware evidence (Roll 47/48, 2026-09-19):
                        # 0=normal, 1=slow, 2=rear, 3=red_eye, 4=red_eye_slow
                        # observed. 5/6/7 remain unobserved with normal
                        # user operation and are left semantic unknown, not
                        # guessed. rec[12] bit 7 is not part of this field.
                        "flash_sync": {
                            0: "normal",
                            1: "slow",
                            2: "rear",
                            3: "red_eye",
                            4: "red_eye_slow",
                        }.get(sync_bits, f"unknown(0x{sync_bits:02x})"),
                    }
                )
            frames.append(frame)
            i += record_size
        if film_speed_code is None:
            raise ProtocolError("roll not terminated by trailer byte + 0xFD")
        rolls.append(
            {
                "roll_number": roll_number,
                "film_speed_raw": f"0x{film_speed_code:02x}",
                "film_speed": f100_numeric.display("iso", film_speed_code)[0],
                "film_speed_source": f100_numeric.display("iso", film_speed_code)[1],
                "frame_count": len(frames),
                "frames": frames,
            }
        )

    return {
        "mode": "detailed" if detailed else "simple",
        "roll_count": len(rolls),
        "rolls": rolls,
        "_value_tables": {
            "directory": str(_table_directory(table_dir)),
            "loaded": {name: table is not None for name, table in tables.items()},
            "policy": table_policy,
            "sources_by_code": sources,
        },
        "_note": "Capture-derived default decoding; estimates and unknown codes are identified in _value_tables.sources_by_code. Raw bytes are always preserved.",
    }


