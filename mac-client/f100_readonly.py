# Observed in CameraCompanion.exe (0x631518 / 0x6318cc), not a documented
# Nikon spec. Photo Secretary uses a different (async, non-fixed-delay)
# pattern for the same "00 then command" shape. Treat both as implementation
# artifacts, not protocol requirements — see COLD_START_STATIC_ANALYSIS.md.
ATTENTION_WAIT_S = 0.03
READ_WAIT_S = 0.07
# Photo Secretary uses a 40-second application-layer CQ/LQ timeout.  This is
# not claimed as a Nikon protocol limit, so callers can override it.
DEFAULT_RESPONSE_TIMEOUT_S = 40.0
DEFAULT_LQ_MAX_RESPONSE_LENGTH = 0xFFFF
DEFAULT_POST_FRAME_QUIET_S = 0.25
POLL_READ_S = 0.2
WRITE_TIMEOUT_S = 2.0
SERIAL_CONFIG = {
    "baudrate": 9600,
    "bytesize": 8,
    "parity": "even",
    "stopbits": 2,
    "read_timeout_seconds": POLL_READ_S,
    "write_timeout_seconds": WRITE_TIMEOUT_S,
    "dtr": True, "rts": False,
    "modem_control_profile": "windows_mq_observed_dtr_on_rts_off",
}


def _open_serial_safely(serial_module, port: str):
    """Open using the DTR-on/RTS-off profile observed in Windows MQ tests.

    Set requested line states before open; OS/adapter open-time transitions
    remain platform dependent. exclusive=True retains the advisory POSIX lock.
    This profile is not a claim that DTR-on is necessary on every adapter.
    """
    ser = serial_module.Serial(
        port=None,
        baudrate=9600,
        bytesize=serial_module.EIGHTBITS,
        parity=serial_module.PARITY_EVEN,
        stopbits=serial_module.STOPBITS_TWO,
        timeout=POLL_READ_S,
        write_timeout=WRITE_TIMEOUT_S,
        exclusive=True,
    )
    try:
        ser.dtr = True
        ser.rts = False
        ser.port = port
        ser.open()
    except BaseException:
        try:
            ser.close()
        except BaseException:
            pass
        raise
    return ser

# Construction and live transmission are deliberately separate policies.
# LQ frame construction remains available for offline fixtures and decoding,
# while live LQ requires the module-private capability issued only by the
# explicit CLI --experimental-live path. Python cannot protect against a
# caller intentionally importing private internals, but this prevents normal
# library/API use from accidentally bypassing the live gate.
_READ_ONLY_FRAME_OPCODES = frozenset({"CQ", "MQ", "OQ", "LQ"})
_DEFAULT_LIVE_OPCODES = frozenset({"CQ", "MQ", "OQ"})
_READ_ONLY_LITERAL_FRAMES = {
    "CQ": b"CQ\x00\x00",
    "MQ": b"MQ\x00\x00",
    "OQ": b"OQ\x00\x00",
    "LQ": b"LQ\x00\x00",
}
_EXPERIMENTAL_LQ_LIVE_CAPABILITY = object()
_LIVE_TRANSPORT_AUTHORITY = object()
_VERIFIED_LIVE_BINDING_AUTHORITY = object()


class ProtocolError(ValueError):
    """The bytes do not form a valid observed F100 frame."""


class ObservedNonSuccessStatus(ProtocolError):
    """The camera returned 0x79, whose official Nikon meaning is unknown."""


@dataclass(frozen=True)
class _LiveTransportAuthorization:
    authority: object
    port: str
    capture_identity: int
    integration_session_id: str


@dataclass(frozen=True)
class _VerifiedLiveBinding:
    """Opaque result issued only after the shared P3 verifier succeeds."""

    authority: object
    integration: dict


def _issue_live_transport_authorization(
    *, port: str, capture: CaptureSession, verified_binding: _VerifiedLiveBinding
) -> _LiveTransportAuthorization:
    """Issue the private open capability after the CLI's P3 verification."""
    if type(port) is not str or not port:
        raise ProtocolError("live authorization requires an exact serial port")
    if (
        type(verified_binding) is not _VerifiedLiveBinding
        or verified_binding.authority is not _VERIFIED_LIVE_BINDING_AUTHORITY
        or type(verified_binding.integration) is not dict
    ):
        raise ProtocolError("live authorization requires a verified P3 binding")
    integration = verified_binding.integration
    if integration.get("candidate_live_blocked") is True:
        raise ProtocolError("Candidate live access blocked; create fresh evidence under the approved policy")
    if (integration.get("operation_scope") in ("record-settings", "erase-records") or
            integration.get("binding_schema") == "f100-reconnect-binding/0.1"):
        import f100_operation_scope as operations
        try:
            operations.validate_live_policy(integration)
        except ValueError as exc:
            raise ProtocolError(str(exc)) from exc
    if integration.get("verified_before_device_open") is not True:
        raise ProtocolError("live authorization was not verified before device open")
    if integration.get("serial_port") != port:
        raise ProtocolError("live authorization serial port mismatch")
    session_id = integration.get("session_id")
    if type(session_id) is not str or not session_id:
        raise ProtocolError("live authorization session ID is missing")
    if capture is None or capture.integration != integration:
        raise ProtocolError("live authorization is not bound to the capture session")
    return _LiveTransportAuthorization(
        authority=_LIVE_TRANSPORT_AUTHORITY,
        port=port,
        capture_identity=id(capture),
        integration_session_id=session_id,
    )


@dataclass(frozen=True)
class CameraResponse:
    status: int
    data: bytes
    raw: bytes

    def require_success(self) -> bytes:
        if self.status == STATUS_SUCCESS:
            return self.data
        if self.status == STATUS_OBSERVED_NON_SUCCESS:
            raise ObservedNonSuccessStatus(
                f"camera returned observed non-success status 0x{self.status:02x}"
            )
        raise ProtocolError(f"unobserved camera status 0x{self.status:02x}")


def encode_request(opcode: str, payload: bytes = b"") -> bytes:
    """Encode the opcode/length/payload portion (the separate attention
    0x00 byte is sent on its own, before this).

    This is intentionally not a generic Nikon command encoder. Only the four
    read-only opcodes represented by this client may be constructed, and all
    four requests are payloadless. LQ construction remains available offline;
    its *live transmission* is gated separately.
    """
    if type(opcode) is not str:
        raise ProtocolError("opcode must be exactly two ASCII characters")
    if type(payload) is not bytes:
        raise ProtocolError("payload must be exact built-in bytes")
    if opcode not in _READ_ONLY_FRAME_OPCODES:
        raise ProtocolError(f"opcode {opcode!r} is outside the read-only allowlist")
    if payload:
        raise ProtocolError(f"{opcode}: read-only requests must not contain a payload")
    return _READ_ONLY_LITERAL_FRAMES[opcode]


def _validate_live_request(
    opcode: str,
    payload: bytes = b"",
    *,
    live_capability: Optional[object] = None,
) -> None:
    """Fail closed before any live serial open or write is attempted."""
    # Reuse the construction boundary so unknown/write opcodes and payloads
    # cannot enter the live path through a future caller.
    encode_request(opcode, payload)
    if opcode in _DEFAULT_LIVE_OPCODES:
        return
    if (
        opcode == "LQ"
        and live_capability is _EXPERIMENTAL_LQ_LIVE_CAPABILITY
    ):
        return
    raise ProtocolError(
        "LQ live transmission requires the explicit experimental-live capability"
    )


def _validate_serial_write(
    data: bytes,
    *,
    role: str,
    opcode: str,
    live_capability: Optional[object] = None,
) -> None:
    """Validate the exact bytes at the last boundary before ``ser.write``."""
    if type(data) is not bytes or type(role) is not str or type(opcode) is not str:
        raise ProtocolError("serial write inputs must use exact built-in types")
    _validate_live_request(
        opcode, live_capability=live_capability
    )
    if role == "attention":
        if data != b"\x00":
            raise ProtocolError(f"{opcode}: invalid attention write")
        return
    if role == "command":
        expected = _READ_ONLY_LITERAL_FRAMES[opcode]
        if data != expected:
            raise ProtocolError(
                f"{opcode}: serial command bytes do not match the allowed payloadless frame"
            )
        return
    raise ProtocolError(f"{opcode}: unsupported serial write role {role!r}")


class ResponseDecoder:
    """Incrementally reconstruct responses split across arbitrary reads.

    Same design as the audited f100link/protocol.py ResponseDecoder
    (20/20 regression tests passing as of the 6th re-audit): conservative
    default length cap, explicit reset() after an error, and decoded
    frames are never lost behind a later error in the same feed().
    """

    def __init__(self, *, maximum_length: int = 512) -> None:
        if not (1 <= maximum_length <= 0xFFFF):
            raise ValueError("maximum_length must be between 1 and 65535")
        self.maximum_length = maximum_length
        self._buffer = bytearray()

    @property
    def buffered(self) -> bytes:
        return bytes(self._buffer)

    def reset(self) -> bytes:
        dropped, self._buffer = bytes(self._buffer), bytearray()
        return dropped

    def feed(self, data: bytes) -> list[CameraResponse]:
        self._buffer.extend(data)
        decoded: list[CameraResponse] = []
        while len(self._buffer) >= 2:
            length = int.from_bytes(self._buffer[:2], "big")
            if length < 1:
                if decoded:
                    return decoded
                raise ProtocolError("response length must include at least a status byte")
            if length > self.maximum_length:
                if decoded:
                    return decoded
                raise ProtocolError(
                    f"response length {length} exceeds configured maximum {self.maximum_length}"
                )
            frame_size = 2 + length
            if len(self._buffer) < frame_size:
                break
            raw = bytes(self._buffer[:frame_size])
            del self._buffer[:frame_size]
            decoded.append(CameraResponse(status=raw[2], data=raw[3:], raw=raw))
        return decoded


class F100Link:
    """One open/close cycle per request.

    This matches only the *Camera Companion*-observed transport shape
    (single open, `00` attention, fixed 30ms wait, command, read). Photo
    Secretary is NOT the same: static analysis shows it sends attention
    `00` as a separate queued no-reply/purge/10ms/close operation, then
    opens a *new* port for MQ. Do not claim this class matches both —
    it is `camera_companion_observed` transport only. See the corrective
    audit (docs/VALIDATION.md) §2 P1."""

    def __init__(
        self,
        port: str,
        *,
        verbose: bool = False,
        response_timeout: float = DEFAULT_RESPONSE_TIMEOUT_S,
        post_frame_quiet: float = DEFAULT_POST_FRAME_QUIET_S,
        capture: Optional[CaptureSession] = None,
        live_authorization: Optional[_LiveTransportAuthorization] = None,
    ):
        if not math.isfinite(response_timeout) or not (0 < response_timeout <= 3600):
            raise ValueError("response_timeout must be finite and from 0 through 3600")
        if not math.isfinite(post_frame_quiet) or not (0 <= post_frame_quiet <= 60):
            raise ValueError("post_frame_quiet must be finite and from 0 through 60")
        self.port = port
        self.verbose = verbose
        self.response_timeout = response_timeout
        self.post_frame_quiet = post_frame_quiet
        self.capture = capture
        self._live_authorization = live_authorization

    def _require_live_transport_authorization(self) -> None:
        authorization = self._live_authorization
        if type(authorization) is not _LiveTransportAuthorization:
            raise ProtocolError("live serial access requires the verified CLI P3 binding")
        if (
            authorization.authority is not _LIVE_TRANSPORT_AUTHORITY
            or authorization.port != self.port
            or self.capture is None
            or authorization.capture_identity != id(self.capture)
            or self.capture.integration.get("session_id")
            != authorization.integration_session_id
        ):
            raise ProtocolError("live serial authorization does not match this request")

    def _log(self, msg: str) -> None:
        if self.verbose:
            print(f"  [link] {msg}", file=sys.stderr)

    @contextlib.contextmanager
    def _open(self):
        self._require_live_transport_authorization()
        if serial is None:
            raise RuntimeError("pyserial not installed. Run: pip3 install pyserial")
        if self.capture is not None:
            self.capture.record(
                "serial_open_attempt", port=self.port, serial_config=SERIAL_CONFIG
            )
        try:
            ser = _open_serial_safely(serial, self.port)
        except BaseException as exc:
            if self.capture is not None:
                self.capture.record(
                    "serial_open_failure",
                    exception_type=type(exc).__name__,
                    message=str(exc),
                )
            raise
        try:
            if self.capture is not None:
                self.capture.record("serial_open_success", port=self.port)
            yield ser
        finally:
            try:
                ser.close()
            except BaseException as exc:
                if self.capture is not None:
                    self.capture.record(
                        "serial_close_failure",
                        exception_type=type(exc).__name__,
                        message=str(exc),
                    )
                raise
            else:
                if self.capture is not None:
                    self.capture.record("serial_close_success", port=self.port)

    def _write(
        self,
        ser,
        data: bytes,
        *,
        role: str,
        opcode: str,
        live_capability: Optional[object] = None,
    ) -> None:
        # This is the final, non-bypassable boundary inside this client. Keep
        # it before capture bookkeeping and immediately before ser.write().
        try:
            _validate_serial_write(
                data,
                role=role,
                opcode=opcode,
                live_capability=live_capability,
            )
        except ProtocolError as exc:
            self._record_tx_rejected(
                exc,
                role=role,
                opcode=opcode,
                requested_bytes=len(data) if type(data) is bytes else None,
            )
            raise
        call_id = None
        if self.capture is not None:
            call_id = self.capture.tx_attempt(data, role=role, opcode=opcode)
        try:
            transferred = ser.write(data)
        except BaseException as exc:
            if self.capture is not None and call_id is not None:
                self.capture.tx_exception(
                    call_id, exc, role=role, opcode=opcode
                )
            raise
        if transferred is None:
            transferred = 0
        if self.capture is not None and call_id is not None:
            self.capture.tx_result(
                call_id, data, int(transferred), role=role, opcode=opcode
            )
        if transferred != len(data):
            raise ProtocolError(
                f"{opcode}: short serial write ({transferred}/{len(data)} bytes)"
            )

    def _record_tx_rejected(
        self,
        exc: ProtocolError,
        *,
        role: object,
        opcode: object,
        requested_bytes: Optional[int],
    ) -> None:
        if self.capture is None:
            return
        try:
            self.capture.record(
                "tx_rejected",
                role=role if type(role) is str else "invalid-type",
                opcode=opcode if type(opcode) is str else "invalid-type",
                requested_bytes=requested_bytes,
                reason=str(exc),
            )
        except BaseException:
            # Rejection logging is evidence only.  It must never turn a rejected
            # request into an attempted serial open or write.
            pass

    def _read(self, ser, size: int, *, opcode: str) -> bytes:
        try:
            chunk = ser.read(size)
        except BaseException as exc:
            if self.capture is not None:
                self.capture.read_exception(exc, opcode=opcode)
            raise
        if chunk and self.capture is not None:
            self.capture.rx(bytes(chunk), opcode=opcode)
        return chunk

    def _read_single_response(
        self,
        ser,
        opcode: str,
        *,
        maximum_length: int = 512,
    ) -> CameraResponse:
        """Collect exactly one response frame without discarding trailing data.

        After the first complete frame, continue polling for a short, configurable
        quiet window.  A second complete frame or a partial trailing frame is an
        explicit protocol error until real hardware evidence defines a different
        multi-frame policy.
        """
        decoder = ResponseDecoder(maximum_length=maximum_length)
        overall_deadline = time.monotonic() + self.response_timeout
        quiet_deadline: Optional[float] = None
        responses: list[CameraResponse] = []

        while True:
            now = time.monotonic()
            active_deadline = overall_deadline
            if quiet_deadline is not None:
                active_deadline = min(active_deadline, quiet_deadline)
            if now >= active_deadline:
                break

            chunk = self._read(ser, 128, opcode=opcode)
            if not chunk:
                continue
            self._log(f"<- {chunk.hex(' ')}")
            decoded = decoder.feed(chunk)
            if decoded:
                responses.extend(decoded)
                quiet_deadline = time.monotonic() + self.post_frame_quiet

        if decoder.buffered:
            raise ProtocolError(
                f"{opcode}: trailing partial response ({decoder.buffered.hex(' ')})"
            )
        if not responses:
            raise ProtocolError(
                f"{opcode}: no response within {self.response_timeout:g}s"
            )
        if len(responses) != 1:
            raise ProtocolError(
                f"{opcode}: expected exactly one response frame, got {len(responses)}"
            )
        response = responses[0]
        if self.capture is not None:
            self.capture.record(
                "response_decoded",
                opcode=opcode,
                status=response.status,
                data_bytes=len(response.data),
                raw_hex=response.raw.hex(),
            )
        return response

    def request(
        self,
        opcode: str,
        payload: bytes = b"",
        *,
        expected_len: Optional[int] = None,
        max_response_length: Optional[int] = None,
        live_capability: Optional[object] = None,
    ) -> CameraResponse:
        try:
            _validate_live_request(
                opcode, payload, live_capability=live_capability
            )
            frame = encode_request(opcode, payload)
        except ProtocolError as exc:
            requested_bytes = None
            if type(opcode) is str and len(opcode) == 2 and type(payload) is bytes:
                requested_bytes = 4 + len(payload)
            self._record_tx_rejected(
                exc,
                role="request",
                opcode=opcode,
                requested_bytes=requested_bytes,
            )
            raise
        if max_response_length is None:
            max_response_length = DEFAULT_LQ_MAX_RESPONSE_LENGTH if opcode == "LQ" else 512
        ResponseDecoder(maximum_length=max_response_length)  # validate before serial I/O
        with self._open() as ser:
            self._log(f"open {self.port}")
            # Retry only a complete, empty 79 frame; never retry I/O failures,
            # timeouts, malformed/extra frames or other status values.
            for attempt in range(2):
                self._write(
                    ser,
                    b"\x00",
                    role="attention",
                    opcode=opcode,
                    live_capability=live_capability,
                )
                self._log("-> 00 (attention)")
                time.sleep(ATTENTION_WAIT_S)
                self._write(
                    ser,
                    frame,
                    role="command",
                    opcode=opcode,
                    live_capability=live_capability,
                )
                self._log(f"-> {frame.hex(' ')} ({opcode})")
                time.sleep(READ_WAIT_S)
    
                response = self._read_single_response(
                    ser, opcode, maximum_length=max_response_length
                )
                if response.status != STATUS_OBSERVED_NON_SUCCESS:
                    break
                if response.data:
                    raise ProtocolError("0x79 response must not contain a payload")
                if attempt == 0:
                    if self.capture is not None:
                        self.capture.record("status_79_retry", opcode=opcode, retry=1)
                    time.sleep(0.3)

        if (
            expected_len is not None
            and response.status == STATUS_SUCCESS
            and len(response.data) != expected_len
        ):
            self._log(
                f"warning: {opcode} data length {len(response.data)} != expected {expected_len}"
            )
        return response

    def request_lq_camera_companion_preflight(
        self,
        *,
        max_response_length: int = DEFAULT_LQ_MAX_RESPONSE_LENGTH,
        live_capability: Optional[object] = None,
    ) -> CameraResponse:
        """Read MQ and OQ before experimental LQ.

        Each request owns its one conditional 79 retry, avoiding nested retries.
        The reference apps and the CS15 experiment support conditional retry,
        not a fixed two-round exchange. LQ remains capability-gated.
        """
        _validate_live_request(
            "LQ", live_capability=live_capability
        )
        mq = self.request("MQ", expected_len=1)
        mq_data = mq.require_success()
        if len(mq_data) != 1:
            raise ProtocolError(f"MQ preflight data must be 1 byte, got {len(mq_data)}")
        time.sleep(0.1)

        oq = self.request("OQ", expected_len=2)
        oq_data = oq.require_success()
        if len(oq_data) != 2:
            raise ProtocolError(f"OQ preflight data must be 2 bytes, got {len(oq_data)}")
        oq_value = int.from_bytes(oq_data, "big")
        if oq_value:
            time.sleep(0.1)

        return self.request(
            "LQ", max_response_length=max_response_length,
            live_capability=live_capability,
        )


# ---- CQ: 4-byte Custom Settings block --------------------------------------

# The upstream research checked 22 custom settings across three camera states.
# This public decoder currently exposes only CSM01/CSM17; this is an
# implementation limit, not the full extent of the upstream observations.
# Preserve raw bytes until the remaining decoders are implemented.
CSM_BITS_CONFIRMED = {
    1: (1, 0, "Automatic film rewind at end of roll"),
    17: (3, 7, "LCD illuminator activated by any button"),
}


def decode_cq(data: bytes) -> dict:
    if len(data) != 4:
        raise ProtocolError(f"CQ block must be 4 bytes, got {len(data)}")
    result: dict = {"raw_hex": data.hex(" ")}
    for number, (byte_idx, bit_idx, note) in CSM_BITS_CONFIRMED.items():
        result[f"CSM{number:02d}"] = {
            "value": bool(data[byte_idx] & (1 << bit_idx)),
            "note": note,
        }
    result["_note"] = (
        "This decoder exposes only CSM01/CSM17. Upstream observations cover all 22 settings; "
        "the remaining decoders are not implemented here. See raw_hex."
    )
    return result


# ---- MQ: 1-byte shooting-data settings -------------------------------------

def decode_mq(data: bytes) -> dict:
    if len(data) != 1:
        raise ProtocolError(f"MQ must be 1 byte, got {len(data)}")
    byte = data[0]
    return {
        "raw_hex": f"{byte:02x}",
        "raw_bin": f"{byte:08b}",
        "memory_full_action": "delete_old_data" if (byte & 0x01) else "stop_shooting",
        "record_shooting_data": bool(byte & 0x02),
        "recording_mode": "detailed" if (byte & 0x08) else "simple",
        "_note": (
            "Bits 0, 1 and 3 were checked against observed camera settings. "
            "Other bits have unknown meanings and must be "
            "preserved on any future write path (not implemented here)."
        ),
    }


