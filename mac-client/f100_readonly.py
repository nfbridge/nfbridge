"""f100_readonly.py — Nikon F100 10-pin read-only client.

READ-ONLY BY DESIGN. Implements CQ / MQ / OQ / LQ only.
`NP`, `DP`, `EP`, unknown opcodes, command payloads, and any EEPROM write are
intentionally NOT implemented. The same allowlist is enforced at request
construction, the live request API, and immediately before serial write. See
the public draft's docs/SAFETY.md and do not weaken this boundary casually.

The upstream implementation completed a physical Mac/F100 read on 2026-09-13.
Its 5-roll, 117-frame payload matched both Windows reference applications.
This public derivative is verified offline; see docs/VALIDATION.md for scope.

Offline usage needs only Python 3. Install pyserial only for live commands.

Usage:
    python3 f100_readonly.py ports              # list candidate serial devices
    python3 f100_readonly.py id                 # show a newly attached cable's USB ID
    python3 f100_readonly.py tables --table-dir DIR  # validate all four TSVs
    python3 f100_readonly.py lq --fixture dump.hex   # decode a captured LQ payload offline
    python3 f100_readonly.py compare --reference expected.json --capture dump.hex

Live CQ/MQ/OQ syntax is generated by mac-connection/f100_orchestrator.py and
requires the exact session ID, plan, admission report, final gate, port, and
new capture directory. LQ keeps the additional --experimental-live gate.

The safety policy requires observing the reference application's LQ traffic
before this client sends LQ live — CQ/MQ/OQ are allowed once electrical
validation and a successful connection are confirmed, but LQ specifically
is gated behind that observed-traffic step. So `lq` refuses to transmit
unless `--experimental-live` is passed explicitly, and prints an
unverified-hardware warning when it does. Prefer `--fixture` (decode a
raw hex/binary capture offline) whenever possible.

Optional: place separately obtained lq_shutter_speed_table.tsv /
lq_aperture_table.tsv / lq_focal_length_table.tsv /
lq_ev_compensation_table.tsv next to this script to get physical-unit LQ
decoding instead of raw codes. These externally derived tables are NOT bundled
or hardcoded here on purpose. The TSVs are tab-separated with CSV-style
quoting (e.g. the shutter table's raw 0xFD row is quoted and doubled to
encode a trailing inch/seconds mark, displaying as 1.5 seconds), so they
are parsed with the `csv` module, not a naive `str.split("\t")`.

Offline LQ decoding defaults to capture-derived formulas when no table is present. Use `--table-policy strict`
to fail closed or `--table-policy raw` to explicitly accept raw-code fallback.
Run the `tables` command to validate filenames, headers, row widths, byte ranges,
hex/decimal agreement, and duplicate codes before decoding a capture.
"""

